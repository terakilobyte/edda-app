        assert_eq!(internals, ["Slot01_Size8", "Slot02_Size7", "Slot03_Size6", "Slot04_Size5", "Slot05_Size4", "Slot06_Size4", "Slot07_Size3", "Slot08_Size3", "Slot11_Size2", "Slot12_Size1", "PlanetaryApproachSuite"]);
