//! Which slots a hull has and what fits in each — the game's outfitting
//! facts, so a build can be planned on a ship the commander does not own
//! yet and a module can be swapped without offering one the slot refuses
//! (maintainer, 2026-09-20: "for the ships we'll have to actually build
//! in their exact slotting and what module types can go where").
//!
//! The tables are `data/ship_slots.json` (per hull: every slot with the
//! journal's own name, its size, and what it takes) and
//! `data/module_kinds.json` (per module symbol: its kind, class, the
//! hulls it is bound to, and how many a ship may carry). Both are
//! generated by `docs/benches/knobs/gen_ship_slots.py` and pinned against
//! the vendored Coriolis sizes and the maintainer's own journal Loadouts
//! (`docs/benches/2026-09-20-ship-slots-pin.csv`: every fitted slot of
//! twelve ships named in the table). The slot NAMES matter: the journal
//! numbers a hull's internals with gaps (the Anaconda has no Slot11 or
//! Slot12; the Type-10's Slot11 comes after its two military slots), so
//! they are per-hull facts, not a rule.
//!
//! The rules, in order: the slot's own list of kinds when it has one
//! (core slots, military slots, the Type-11's mining hardpoints and
//! limpet slot, the Panther's cargo slots, the Caspian's cabins), else
//! the slot family's kinds; class no larger than the slot; life support,
//! sensors and the SCO drives exactly the slot's size; a hull-bound
//! module (fighter hangars, luxury cabins, the Panther's Mk II racks)
//! only on its hulls.

use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use std::collections::HashMap;

/// One slot of a hull.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Slot {
    /// The journal's `Slot` value (`Slot11_Size2`, `Military01`, `LargeHardpoint1`, `PowerPlant`).
    pub slot: String,
    /// hardpoint | utility | core | military | internal
    pub group: String,
    /// 0 for utility mounts; 1..=8 otherwise.
    pub size: i64,
    /// Kinds this slot takes, when it is narrower than its family.
    #[serde(default)]
    pub only: Vec<String>,
    /// The module must be exactly the slot's size (life support, sensors).
    #[serde(default)]
    pub exact_size: bool,
}

#[derive(Debug, Clone, Deserialize)]
struct HullRaw {
    name: String,
    slots: Vec<Slot>,
    #[serde(default)]
    stock: HashMap<String, String>,
}

/// A hull: its slots and its stock fit.
#[derive(Debug, Clone, Serialize)]
pub struct Hull {
    /// The journal's ship symbol, lowercase (`type9_military`).
    pub symbol: String,
    /// The printed name ("Type-10 Defender").
    pub name: String,
    pub slots: Vec<Slot>,
    /// Slot -> module symbol as the ship is sold.
    pub stock: HashMap<String, String>,
}

impl Hull {
    pub fn slot(&self, name: &str) -> Option<&Slot> {
        self.slots.iter().find(|s| s.slot.eq_ignore_ascii_case(name))
    }
}

/// What kind of thing a module symbol is.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ModuleKind {
    /// The kind code (`hpl` pulse lasers, `icr` cargo racks, `cfsdo` SCO drives, ...).
    pub kind: String,
    pub class: i64,
    pub rating: String,
    /// The kind's printed name ("Pulse Laser", "Cargo Rack").
    pub name: String,
    #[serde(default)]
    pub mount: Option<String>,
    /// Hulls this module is sold for, when it is bound to some (fighter
    /// hangars, luxury cabins, Mk II racks); empty means every hull.
    #[serde(default)]
    pub ships: Vec<String>,
    /// How many of its pool a ship may carry, when limited (one shield
    /// generator, one hangar, four experimental weapons, ...).
    #[serde(default)]
    pub limit: Option<i64>,
    /// The pool that limit counts over. A pool is not a kind: every AX and
    /// Guardian weapon shares "hex"; the docking computer ("ifa_dc") and the
    /// supercruise assist ("ifa_sc") are one kind but two pools.
    #[serde(default)]
    pub limit_group: Option<String>,
    /// A pool this module widens, and by how much: the Experimental Weapon
    /// Stabiliser allows one more experimental weapon (class 3) or two (class 5).
    #[serde(default)]
    pub unlimit: Option<String>,
    #[serde(default)]
    pub unlimit_count: i64,
    /// Must be exactly the slot's size (SCO drives).
    #[serde(default)]
    pub exact_size: bool,
}

/// The kinds each slot family takes.
fn family_kinds(group: &str) -> &'static [&'static str] {
    match group {
        "hardpoint" => &["hel", "hul", "hc", "hex", "hexxm", "hexxc", "hexgg", "hexgp", "hexgs", "hexsc", "hextp", "hfc", "hm", "hmtl", "hmtm", "hmr", "hmc", "hpa", "hpl", "hrg", "htp"],
        "utility" => &["ucl", "uec", "uex", "uhsl", "ukws", "ucs", "upd", "upwa", "usb", "ufsws"],
        "military" => &["ihrp", "isrp", "imahrp", "imrp", "iscb"],
        "internal" => &[
            "iafmu", "icr", "iclc", "idlc", "iex", "ifh", "ifa", "ifsdb", "ifsdi", "ifs", "cft", "iftlc", "ihblc", "ihrp", "isrp", "imahrp", "imrp", "imlc", "ipc", "ipvh", "iplc", "inlc", "ir",
            "irlc", "islc", "iscb", "isg", "iss", "ipas",
        ],
        _ => &[],
    }
}

/// The swap that removes a module: the slot is left empty. Every slot but
/// a core one may be (maintainer, 2026-09-20: "need the option to remove an
/// item, i.e. leave empty on every slot").
pub const EMPTY: &str = "empty";
/// The limit pool every experimental weapon (AX and Guardian) shares.
pub const EXPERIMENTAL_POOL: &str = "hex";

/// A module a technology broker sells already engineered: the plain item's
/// symbol with a fixed engineering block and no engineer named — the way it
/// reads in the journal (the maintainer's Kestrel, 2026-08-23: a size 4 SCO
/// drive from the human broker with Increased Range grade 5 at quality 1.0,
/// Mass Manager added by him the next day). `data/preengineered.json`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Preset {
    pub id: String,
    /// The journal item symbol, lowercase.
    pub item: String,
    /// The printed name ("Frame Shift Drive (SCO) 5A · pre-engineered V1").
    pub name: String,
    /// human | guardian
    pub broker: String,
    /// The journal's blueprint symbol (`FSD_LongRange`).
    pub blueprint: String,
    pub level: i64,
    pub quality: f64,
    /// The fixed engineering as the journal's `Modifiers` state it: label
    /// -> multiplier on the base value (Mass 1.3, FSDOptimalMass 1.7, ...).
    /// Read from a real Loadout, so the figures are the game's, not a roll.
    #[serde(default)]
    pub modifiers: HashMap<String, f64>,
}

pub struct Slots {
    hulls: HashMap<String, Hull>,
    kinds: HashMap<String, ModuleKind>,
    presets: Vec<Preset>,
}

impl Slots {
    pub fn load() -> Self {
        let raw: HashMap<String, HullRaw> = serde_json::from_str(include_str!("../data/ship_slots.json")).expect("ship_slots.json parses");
        let hulls = raw
            .into_iter()
            .map(|(symbol, h)| {
                let stock = h.stock.into_iter().map(|(k, v)| (k, v.to_ascii_lowercase())).collect();
                (symbol.clone(), Hull { symbol, name: h.name, slots: h.slots, stock })
            })
            .collect();
        let kinds = serde_json::from_str(include_str!("../data/module_kinds.json")).expect("module_kinds.json parses");
        let presets: Vec<Preset> = serde_json::from_str(include_str!("../data/preengineered.json")).expect("preengineered.json parses");
        Slots { hulls, kinds, presets }
    }

    /// The pre-engineered variants sold of this item.
    pub fn presets_for(&self, item: &str) -> Vec<&Preset> {
        self.presets.iter().filter(|p| p.item.eq_ignore_ascii_case(item)).collect()
    }

    pub fn preset(&self, id: &str) -> Option<&Preset> {
        self.presets.iter().find(|p| p.id == id)
    }

    /// By the journal's ship symbol or the printed name.
    pub fn hull(&self, symbol_or_name: &str) -> Option<&Hull> {
        let key = symbol_or_name.to_ascii_lowercase();
        self.hulls.get(&key).or_else(|| self.hulls.values().find(|h| h.name.eq_ignore_ascii_case(symbol_or_name)))
    }

    /// Every hull, by printed name.
    pub fn hulls(&self) -> Vec<&Hull> {
        let mut v: Vec<&Hull> = self.hulls.values().collect();
        v.sort_by(|a, b| a.name.cmp(&b.name));
        v
    }

    pub fn kind(&self, item: &str) -> Option<&ModuleKind> {
        let item = item.to_ascii_lowercase();
        // The `_free` early-access variant of a module is that module (the
        // Type-11's hangar as delivered: `int_mkiilargebuggybay_size4_class3_free`).
        self.kinds.get(&item).or_else(|| self.kinds.get(item.strip_suffix("_free")?))
    }

    /// Whether `item` may go in `slot` of `hull`; the reason when not, as
    /// the commander reads it.
    pub fn fits(&self, hull: &Hull, slot: &Slot, item: &str) -> Result<(), String> {
        if item.eq_ignore_ascii_case(EMPTY) {
            return if slot.group == "core" { Err(format!("{} cannot be empty", ed_journal::modules::slot_name(&slot.slot))) } else { Ok(()) };
        }
        let Some(k) = self.kind(item) else { return Err(format!("{} is not a module the outfitting tables know", ed_journal::modules::item_name(item))) };
        let allowed: Vec<&str> = if slot.only.is_empty() { family_kinds(&slot.group).to_vec() } else { slot.only.iter().map(String::as_str).collect() };
        if !allowed.iter().any(|a| *a == k.kind) {
            return Err(format!("{} does not take a {}", ed_journal::modules::slot_name(&slot.slot), k.name.to_ascii_lowercase()));
        }
        if k.class > slot.size {
            return Err(format!("class {} is too large for {} (size {})", k.class, ed_journal::modules::slot_name(&slot.slot), slot.size));
        }
        if (slot.exact_size || k.exact_size) && k.class != slot.size {
            return Err(format!("{} takes exactly class {}", ed_journal::modules::slot_name(&slot.slot), slot.size));
        }
        if !k.ships.is_empty() && !k.ships.iter().any(|s| s.eq_ignore_ascii_case(&hull.symbol)) {
            return Err(format!("{} is not sold for the {}", ed_journal::modules::item_name(item), hull.name));
        }
        // Hull-bound racks and limpet controllers go in the slots named for them.
        if !k.ships.is_empty() {
            let upper = slot.slot.to_ascii_uppercase();
            if k.kind == "icr" && !upper.starts_with("CARGO") {
                return Err(format!("{} goes in a cargo slot", ed_journal::modules::item_name(item)));
            }
            if k.kind == "imlc" && !upper.starts_with("LIMPETCONTROLLER") {
                return Err(format!("{} goes in the limpet controller slot", ed_journal::modules::item_name(item)));
            }
        }
        Ok(())
    }

    /// Every module that fits `slot` of `hull`: by kind name, then class
    /// (largest first), then rating.
    pub fn candidates(&self, hull: &Hull, slot: &Slot) -> Vec<(&str, &ModuleKind)> {
        let mut out: Vec<(&str, &ModuleKind)> = self.kinds.iter().filter(|(item, _)| !item.eq_ignore_ascii_case(EMPTY) && self.fits(hull, slot, item).is_ok()).map(|(item, k)| (item.as_str(), k)).collect();
        out.sort_by(|a, b| a.1.name.cmp(&b.1.name).then(b.1.class.cmp(&a.1.class)).then(a.1.rating.cmp(&b.1.rating)).then(a.1.mount.cmp(&b.1.mount)));
        out
    }

    /// Modules a ship may carry only so many of, over the whole fit (fitted
    /// plus swapped): "two shield generators" and the like. Counted by pool,
    /// with the stabiliser's allowance — the kind-wise count called the
    /// maintainer's Python Mk II as flown (six shard cannons on a class 5
    /// stabiliser, a docking computer beside a supercruise assist)
    /// impossible (2026-09-26); the journal is the measurement.
    pub fn over_limit(&self, items: &[(String, String)]) -> Vec<String> {
        let mut count: HashMap<&str, (i64, &ModuleKind)> = HashMap::new();
        let mut widened: HashMap<&str, i64> = HashMap::new();
        for (_, item) in items {
            let Some(k) = self.kind(item) else { continue };
            if let (Some(pool), Some(_)) = (k.limit_group.as_deref(), k.limit) {
                count.entry(pool).or_insert((0, k)).0 += 1;
            }
            if let Some(pool) = k.unlimit.as_deref() {
                *widened.entry(pool).or_insert(0) += k.unlimit_count;
            }
        }
        let mut out: Vec<String> = count
            .iter()
            .filter_map(|(pool, (n, k))| {
                let extra = widened.get(pool).copied().unwrap_or(0);
                let cap = k.limit? + extra;
                if *n <= cap {
                    return None;
                }
                let what = if *pool == EXPERIMENTAL_POOL { "experimental weapons (AX and Guardian together)".to_string() } else { k.name.to_ascii_lowercase() };
                let how = match (*pool == EXPERIMENTAL_POOL, extra) {
                    (true, 0) => "; an Experimental Weapon Stabiliser allows one more (class 3) or two more (class 5)",
                    (true, _) => " with the stabiliser fitted",
                    _ => "",
                };
                Some(format!("{n} × {what}: a ship carries at most {cap}{how}"))
            })
            .collect();
        out.sort();
        out
    }

    /// The hull as sold, shaped like a journal `Loadout`, so every reader
    /// of a Loadout (figures, plan, import, SLEF) works on a ship the
    /// commander does not have yet.
    pub fn stock_loadout(&self, hull: &Hull) -> Value {
        let mut modules = Vec::new();
        let mut fuel = 0.0;
        let mut cargo = 0i64;
        for s in &hull.slots {
            let Some(item) = hull.stock.get(&s.slot) else { continue };
            if let Some(k) = self.kind(item) {
                match k.kind.as_str() {
                    "cft" if s.slot == "FuelTank" => fuel = (1i64 << k.class) as f64,
                    "icr" => cargo += 1i64 << k.class,
                    _ => {}
                }
            }
            modules.push(json!({ "Slot": s.slot, "Item": item, "On": true, "Priority": 1 }));
        }
        modules.push(json!({ "Slot": "ShipCockpit", "Item": format!("{}_cockpit", hull.symbol), "On": true, "Priority": 1 }));
        modules.push(json!({ "Slot": "CargoHatch", "Item": "modularcargobaydoor", "On": true, "Priority": 2 }));
        json!({
            "event": "Loadout",
            "Ship": hull.symbol,
            "Ship_Localised": hull.name,
            "ShipID": Value::Null,
            "ShipName": "",
            "ShipIdent": "",
            "Stock": true,
            "FuelCapacity": { "Main": fuel, "Reserve": 0.0 },
            "CargoCapacity": cargo,
            "Modules": modules,
        })
    }
}

